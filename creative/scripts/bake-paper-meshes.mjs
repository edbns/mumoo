/**
 * Regenerates src/paper-mesh-data.ts from svg-mesh-3d (MIT).
 * Run: node scripts/bake-paper-meshes.mjs
 */
import svgMesh3d from 'svg-mesh-3d';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const PAPER_PATHS = {
  sheet: 'M120,40 C200,10 340,20 420,55 C500,90 520,180 490,280 C460,380 360,440 250,450 C140,460 40,400 25,290 C10,180 40,70 120,40 Z',
  star: 'M250,20 L295,160 L450,160 L325,250 L370,400 L250,310 L130,400 L175,250 L50,160 L205,160 Z',
  bird: 'M40,180 C80,80 160,90 200,150 C240,90 320,70 380,120 C300,140 260,180 240,210 C220,250 160,280 100,250 C70,235 50,210 40,180 Z',
};

function round(n) {
  return Math.round(n * 1e5) / 1e5;
}

const out = {};
for (const [name, path] of Object.entries(PAPER_PATHS)) {
  const randomization = name === 'sheet' ? 36 : name === 'bird' ? 16 : 8;
  const mesh = svgMesh3d(path, {
    scale: 2,
    simplify: 1,
    randomization,
    normalize: true,
    delaunay: true,
    clean: true,
  });
  out[name] = {
    path,
    positions: mesh.positions.map(p => [round(p[0]), round(p[1])]),
    cells: mesh.cells.map(c => [...c]),
  };
  console.log(name, out[name].positions.length, 'verts', out[name].cells.length, 'tris');
}

const src = `/** Auto-generated by scripts/bake-paper-meshes.mjs — do not edit by hand. */
export type BakedMesh = { path: string; positions: number[][]; cells: number[][] };

export const BAKED_PAPER_MESHES = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, BakedMesh>;
`;

writeFileSync(join(root, 'src/paper-mesh-data.ts'), src);
console.log('wrote src/paper-mesh-data.ts');
